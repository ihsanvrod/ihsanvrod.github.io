export function getTranslation(key: string, language: string = 'English'): string {
  return translations[language]?.[key] || translations.English[key] || key;
}

export function speak(text: string, language: string = 'English') {
  const isScreenReaderEnabled = localStorage.getItem('accessibility_screenReader');
  if (!isScreenReaderEnabled || JSON.parse(isScreenReaderEnabled) !== true) {
    return;
  }

  // Cancel any ongoing speech
  window.speechSynthesis.cancel();

  const utterance = new SpeechSynthesisUtterance(text);

  // Map language to speech synthesis language codes
  const languageMap: Record<string, string> = {
    'English': 'en-US',
    'Spanish': 'es-ES',
    'French': 'fr-FR',
    'German': 'de-DE',
    'Chinese': 'zh-CN',
    'Japanese': 'ja-JP',
    'Korean': 'ko-KR',
    'Portuguese': 'pt-PT',
    'Italian': 'it-IT',
    'Russian': 'ru-RU',
    'Arabic': 'ar-SA'
  };

  utterance.lang = languageMap[language] || 'en-US';
  utterance.rate = 1.0;
  utterance.pitch = 1.0;
  utterance.volume = 1.0;

  window.speechSynthesis.speak(utterance);
}
